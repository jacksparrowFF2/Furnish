'use strict';
const assert=require('node:assert/strict'),DXF=require('../src/io/dxf-import.js');
const poly=(layer,points)=>`0\nLWPOLYLINE\n8\n${layer}\n70\n1\n${points.map(p=>`10\n${p[0]}\n20\n${p[1]}\n`).join('')}`;
const rectangle=(layer,w,h)=>poly(layer,[[0,0],[w,0],[w,h],[0,h]]);
const raw=`0\nSECTION\n2\nHEADER\n9\n$INSUNITS\n70\n4\n0\nENDSEC\n0\nSECTION\n2\nENTITIES\n${rectangle('承重墙',230,2000)}${rectangle('窗户',240,1200)}${rectangle('房屋',230,2000)}${rectangle('房间中心线',4000,3000)}0\nCIRCLE\n8\n房屋\n10\n0\n20\n0\n40\n10\n0\nINSERT\n8\n块参考\n2\n墙块\n0\nENDSEC\n0\nEOF\n`;
const parsed=DXF.parse(raw),before=structuredClone(parsed),report=DXF.inspect(parsed,{layers:['房屋','承重墙']});
assert.equal(DXF.layerRole('承重墙').kind,'b');
assert.equal(DXF.layerRole('非承重墙').kind,'n');
assert.equal(DXF.layerRole('房屋').kind,'');
assert.equal(DXF.layerRole('窗户').role,'window');
assert.equal(DXF.layerRole('FURNISH_WINDOW_GUIDE').role,'window');
assert.equal(DXF.layerRole('飘窗').role,'bay');
assert.equal(DXF.layerRole('FURNISH_PARTITION_120').kind,'n');
assert.equal(report.layers.find(l=>l.name==='承重墙').profiles,1);
assert.equal(report.layers.find(l=>l.name==='房间中心线').profiles,0);
assert.equal(report.layers.find(l=>l.name==='窗户').rectangles.length,1);
assert.deepEqual(report.layers.find(l=>l.name==='窗户').rectangles[0],{id:1,width:240,height:1200});
assert.equal(report.layers.find(l=>l.name==='房屋').unsupportedGeometry,1);
assert.equal(report.layers.find(l=>l.name==='块参考').types.INSERT,1);
assert.equal(report.warnings.find(w=>w.code==='overlapping-layers').count,4);
assert.equal(report.warnings.filter(w=>w.code==='wall-profiles').length,2);
assert.ok(report.warnings.some(w=>w.code==='unsupported-geometry'));
assert.ok(!report.warnings.some(w=>w.code==='reference-as-wall'));
assert.ok(DXF.inspect(parsed,{layers:['窗户']}).warnings.some(w=>w.code==='reference-as-wall'));
assert.equal(DXF.inspect(parsed,{layers:['房屋'],mmPerUnit:10}).layers.find(l=>l.name==='承重墙').profiles,0);
assert.equal(DXF.inspect(parsed,{layers:['房屋'],mmPerUnit:0}).mmPerUnit,null);
assert.deepEqual(parsed,before);
// A concave room's bounding box is not a rectangular opening candidate.
const concave=DXF.parse(`0\nSECTION\n2\nENTITIES\n${poly('窗户',[[0,0],[2000,0],[2000,240],[1000,240],[1000,600],[0,600]])}0\nENDSEC\n0\nEOF\n`);
assert.equal(DXF.inspect(concave,{mmPerUnit:1}).layers[0].rectangles.length,0);
console.log('PASS layer intent, outline/room distinction, rectangular references, unsupported geometry inventory, cross-layer overlaps, units and immutable inspection');
