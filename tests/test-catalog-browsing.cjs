'use strict';
const assert=require('node:assert/strict'),C=require('../src/data/catalog.js');
const original=JSON.stringify(C.library),browse=C.browseLibrary(),items=C.library.flatMap(g=>g.items);
assert.equal(browse.flatMap(g=>g.items).length,items.length);
assert.equal(new Set(browse.flatMap(g=>g.items)).size,items.length);
for(const it of items){assert(browse.some(g=>g.items.includes(it)));assert.equal(C.findItem(it[0],it[1]),it);}
assert.deepEqual(browse.find(g=>g.cat==='宠物').items.map(it=>it[0]).sort(),['aquarium_mijia_2pro','cat_tree','litter_box','pet_feeder_mijia_2']);
assert(browse.find(g=>g.cat==='洗衣 · 家政').items.some(it=>it[0]==='dryingrack'));
assert.equal(browse.find(g=>g.cat==='柜体').items.length,9);
assert.equal(JSON.stringify(C.library),original);
const item=type=>items.find(it=>it[0]===type),aircon=item('aircon_midea_ultra_2hp'),washer=item('washer');
assert.equal(C.itemHeight(item('wardrobe')),2200);
assert.equal(C.itemHeight(item('nightstand')),500);
assert.equal(C.itemHeight(item('tea_table_800')),720);
assert.equal(C.itemHeight(item('bed')),undefined);
assert(C.matches(aircon,{query:'MIDEA N8KS1-1U'}));
assert(C.matches(aircon,{query:'客厅 ultra'}));
assert(!C.matches(aircon,{query:'Midea missing'}));
assert(C.matches(washer,{use:'laundry',maxWidth:600,maxDepth:600}));
assert(!C.matches(washer,{maxWidth:599}));assert(!C.matches(washer,{maxDepth:599}));
assert(!C.matches(washer,{use:'kitchen'}));
assert(C.matches(washer,{query:'  LAUNDRY  ',use:'laundry'}));
for(const it of browse.find(g=>g.cat==='洗衣 · 家政').items)assert(C.itemUses(it).includes('laundry'));
const counter=item('counter');assert(C.itemUses(counter).includes('laundry'));
assert(C.itemUses(items.find(it=>it[0]==='counter'&&!it[10])).includes('kitchen'));
const custom=['custom','自定义柜',800,400,'#fff',0,900,'custom-1'];
assert(C.matches(custom,{query:'品牌 型号'},{brand:'品牌',model:'型号'}));
assert(C.matches(custom,{query:'custom cabinet'},{name:'Custom cabinet'}));
assert(!C.matches(custom,{use:'laundry'}));
assert.equal(C.itemKey(custom),C.itemKey([...custom.slice(0,1),'改名',900,500,'#000',100,1000,'custom-1']));
assert.notEqual(C.itemKey(custom),C.itemKey([...custom.slice(0,7),'custom-2']));
const typesBefore=JSON.stringify(C.typePrices);C.browseLibrary();assert.equal(JSON.stringify(C.typePrices),typesBefore);
assert.equal(C.findItem('wardrobe','小衣柜')[2],1200);
console.log('PASS catalog browsing: complete unique view, unchanged specifications, identity search, combined uses, size boundaries and custom identity');
